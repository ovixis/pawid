// Builds src/icons.ts from MingCute (Apache-2.0, https://github.com/Richard9394/MingCute).
// Add a name to ICONS and run: npm run icons -w @pawid/ui
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const set = JSON.parse(readFileSync(require.resolve("@iconify-json/mingcute/icons.json"), "utf8"));

// Our name -> MingCute name (line style; "-fill" is added for the solid variant).
const ICONS = {
  add: "add", close: "close", check: "check", checkCircle: "check-circle", closeCircle: "close-circle",
  delete: "delete-2", edit: "edit-2", print: "print", share: "share-2", copy: "copy-2", link: "link",
  qr: "qrcode", scan: "scan", camera: "camera", back: "arrow-left", external: "external-link",
  phone: "phone", calendar: "calendar", certificate: "certificate", warning: "warning", info: "information",
  dog: "dog", cat: "cat", paw: "paw", loading: "loading", time: "time", pin: "map-pin", world: "world-2",
  hotel: "hotel", fork: "fork-knife", cup: "teacup", museum: "bank", ticket: "ticket", building: "building-2",
};

const lines = [
  "// Generated by scripts/build-icons.mjs from MingCute (Apache-2.0). Do not edit by hand.",
  "export const ICON_BODIES = {",
];
for (const [name, mc] of Object.entries(ICONS)) {
  for (const [suffix, key] of [["-line", name], ["-fill", `${name}Fill`]]) {
    const icon = set.icons[mc + suffix];
    if (!icon) throw new Error(`MingCute icon not found: ${mc}${suffix}`);
    lines.push(`  ${key}: ${JSON.stringify(icon.body)},`);
  }
}
lines.push("} as const;", "", "export type IconName = keyof typeof ICON_BODIES;", "");
writeFileSync(new URL("../src/icons.ts", import.meta.url), lines.join("\n"));
console.log(`icons.ts: ${Object.keys(ICONS).length * 2} icons`);

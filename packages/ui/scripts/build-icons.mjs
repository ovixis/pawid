// Builds src/icons.ts from Tabler Icons (MIT, https://tabler.io/icons), chosen by the owner on 2026-11-21
// from the PawID Icon Lab (Phosphor, Tabler, Material Symbols, Fluent Emoji; MingCute before).
// Add a name to ICONS and run: npm run icons -w @pawid/ui
// Each icon has a line version (<name>) and a filled one (<name>Fill). Tabler's "-filled" icon is used
// where it exists; otherwise the filled name gives the line icon too.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const set = JSON.parse(readFileSync(require.resolve("@iconify-json/tabler/icons.json"), "utf8"));

// Our name -> Tabler name.
const ICONS = {
  add: "plus", close: "x", check: "check", checkCircle: "circle-check", closeCircle: "circle-x",
  delete: "trash", edit: "pencil", print: "printer", share: "share", copy: "copy", link: "link",
  qr: "qrcode", scan: "scan", camera: "camera", back: "arrow-left", external: "external-link",
  phone: "phone", calendar: "calendar", certificate: "certificate", warning: "alert-triangle", info: "info-circle",
  dog: "dog", cat: "cat", paw: "paw", loading: "loader-2", time: "clock", pin: "map-pin", world: "world",
  hotel: "bed", fork: "tools-kitchen-2", cup: "coffee", museum: "building-bank", ticket: "ticket", building: "building",
  beer: "coffee", beach: "beach", tent: "tent", train: "train", ship: "ship", park: "trees", store: "building-store",
  cellphone: "device-mobile", download: "download", safari: "brand-safari", chrome: "brand-chrome", addSquare: "square-plus",
  moreV: "dots-vertical", shareIos: "upload", idcard: "id", apple: "brand-apple", android: "brand-android", laptop: "device-laptop",
  github: "brand-github", pullRequest: "git-pull-request", translate: "language", bug: "bug", star: "star",
  stethoscope: "stethoscope", vaccine: "vaccine", scale: "scale", code: "code", heartHandshake: "heart-handshake",
  shieldCheck: "shield-check", calendarCheck: "calendar-check", map: "map-2",
  terminal: "terminal-2", chatbot: "message-chatbot", openai: "brand-openai", vscode: "brand-vscode", fileText: "file-text", robot: "robot", sparkles: "sparkles",
};

const lines = ["// Generated by scripts/build-icons.mjs from Tabler Icons (MIT). Do not edit by hand."];
const map = [
  "// Generated by scripts/build-icons.mjs. Do not edit by hand.",
  'import * as I from "./icons";',
  "export const ICON_BODIES = {",
];
for (const [name, tb] of Object.entries(ICONS)) {
  const line = set.icons[tb];
  if (!line) throw new Error(`Tabler icon not found: ${tb}`);
  const fill = set.icons[`${tb}-filled`] ?? line;
  for (const [key, icon] of [[name, line], [`${name}Fill`, fill]]) {
    lines.push(`export const I_${key} = ${JSON.stringify(icon.body)};`);
    map.push(`  ${key}: I.I_${key},`);
  }
}
map.push("} as const;", "", "export type IconName = keyof typeof ICON_BODIES;", "");
writeFileSync(new URL("../src/icons.ts", import.meta.url), lines.join("\n") + "\n");
writeFileSync(new URL("../src/icon-map.ts", import.meta.url), map.join("\n"));
console.log(`icons.ts: ${Object.keys(ICONS).length * 2} icons (Tabler)`);
